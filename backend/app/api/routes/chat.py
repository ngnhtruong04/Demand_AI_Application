"""app.api.routes.chat — DemandAI Conversational Assistant & Model Routing API."""
from __future__ import annotations

import json
import logging
import time
from typing import Any
from fastapi import APIRouter
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field

from app.agent.sku_agent import (
    DEFAULT_MODEL,
    MODELS,
    estimate_tokens,
    get_default_model_name,
    get_llm_api_key,
    stream_sku_agent_response,
)

logger = logging.getLogger(__name__)

router = APIRouter()

BOOT_ID = str(int(time.time()))


class MessageItem(BaseModel):
    """Single message item in a conversational dialogue."""

    role: str = Field(
        ...,
        description="Message author role: 'user', 'assistant', or 'system'",
        examples=["user"],
    )
    text: str = Field(
        ...,
        description="Message text content",
        examples=["Nếu tuần sau tôi giảm giá 20% cho Baguette_40 thì bán được bao nhiêu? Có cứu được deadstock không?"],
    )


class ChatRequest(BaseModel):
    """Payload for conversational inquiry submission."""

    messages: list[MessageItem] = Field(
        ...,
        description="Chronological list of dialogue messages including past context and current user prompt.",
    )
    model: str | None = Field(
        default=None,
        description="Target LLM model identifier (e.g. 'gpt-6-luna'). Defaults to system configured default model.",
        examples=["gpt-6-luna"],
    )
    selected_item_id: str | None = Field(
        default=None,
        description="Active SKU unique_id selected in the dashboard UI for contextual grounding.",
        examples=["4471"],
    )
    session_id: str | None = Field(
        default=None,
        description="Session tracking identifier for persisting multi-turn conversation context.",
        examples=["session-94863c47"],
    )
    temperature: float | None = Field(
        default=0.1,
        ge=0.0,
        le=2.0,
        description="Sampling temperature (lower values ensure strictly factual, deterministic inventory recommendations).",
        examples=[0.1],
    )
    top_p: float | None = Field(
        default=0.9,
        ge=0.0,
        le=1.0,
        description="Nucleus sampling probability threshold.",
        examples=[0.9],
    )
    max_tokens: int | None = Field(
        default=2500,
        ge=100,
        le=8000,
        description="Maximum generation completion tokens (default 2500 ensures full multi-warehouse tables without truncation).",
        examples=[2500],
    )
    stream: bool = Field(
        default=False,
        description="Whether to stream the assistant response as Server-Sent Events (SSE).",
        examples=[False],
    )
    language: str | None = Field(
        default="en",
        description="Preferred response language: 'en' (English) or 'vi' (Vietnamese).",
        examples=["vi"],
    )


class ChatResponse(BaseModel):
    """Structured response from the DemandAI Conversational Assistant."""

    reply: str = Field(
        ...,
        description="Markdown response generated by the assistant, including BLUF, comparison tables, and operational guidance.",
    )
    model: str = Field(
        ...,
        description="Model identifier utilized for generation.",
        examples=["gpt-6-luna"],
    )
    provider: str = Field(
        ...,
        description="Inference provider hosting the model.",
        examples=["openai"],
    )
    used_tokens: int = Field(
        ...,
        description="Total token count consumed by input prompts and output generation.",
        examples=[1240],
    )
    context_size: int = Field(
        ...,
        description="Maximum context window capacity of the active model in tokens.",
        examples=[1000000],
    )
    compacted: bool = Field(
        default=False,
        description="Flag indicating if conversation history underwent compression/compaction.",
        examples=[False],
    )


@router.get(
    "/models",
    summary="List Supported AI Models & Runtime Providers",
    description=(
        "Returns the registry of supported Large Language Models (including GPT-6 Luna), "
        "their context window limits, active API credentials, and current runtime default model."
    ),
    response_description="Active model registry metadata and runtime boot identifier.",
)
def get_models() -> dict[str, Any]:
    """Returns supported models and current default model."""
    default_model = get_default_model_name()
    available = [v for v in MODELS.values() if get_llm_api_key(v)]
    has_openrouter = any(v.get("provider") == "openrouter" for v in available)
    return {
        "default": default_model,
        "models": available,
        "has_openrouter": has_openrouter,
        "boot_id": BOOT_ID,
    }


@router.post(
    "/stream",
    summary="Stream Assistant Dialogue Response (SSE)",
    description=(
        "Streams token-by-token analytical reasoning, tool execution progress, and formatted markdown tables "
        "using Server-Sent Events (SSE). Recommended for responsive real-time chat UX."
    ),
    response_description="Server-Sent Events stream with 'token', 'tool_call', and 'done' events.",
)
async def post_stream(req: ChatRequest):
    """Server-Sent Events (SSE) Streaming endpoint for token-by-token SKU analysis responses."""
    default_model = get_default_model_name()
    model_key = req.model if (req.model and req.model in MODELS) else default_model
    model_info = MODELS.get(model_key) or MODELS.get(default_model) or next(iter(MODELS.values()))

    user_indices = [i for i, m in enumerate(req.messages) if m.role == "user"]
    if user_indices:
        last_idx = user_indices[-1]
        last_user_msg = req.messages[last_idx].text
        history_msgs = req.messages[:last_idx]
    else:
        last_user_msg = req.messages[-1].text if req.messages else ""
        history_msgs = req.messages[:-1]

    history = [{"role": m.role, "content": m.text} for m in history_msgs]

    return StreamingResponse(
        stream_sku_agent_response(
            query=last_user_msg,
            history_messages=history,
            model_info=model_info,
            selected_item_id=req.selected_item_id,
            language=req.language or "en",
            session_id=req.session_id,
        ),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
        },
    )


@router.post(
    "/message",
    response_model=ChatResponse,
    summary="Submit Chat Message (Synchronous or Stream)",
    description=(
        "Processes user inquiries via the LangChain ReAct SKU Agent. Seamlessly evaluates intent, "
        "executes specialized analytics tools (TreeSHAP drivers, replenishment calculations, What-If price simulations), "
        "and returns an executive-grade Markdown analysis."
    ),
    response_description="Structured ChatResponse payload with markdown text and token usage metadata.",
)
async def post_message(req: ChatRequest) -> Any:
    """Unified chat endpoint for synchronous and streaming requests."""
    default_model = get_default_model_name()
    model_key = req.model if (req.model and req.model in MODELS) else default_model
    model_info = MODELS.get(model_key) or MODELS.get(default_model) or next(iter(MODELS.values()))
    context_size = model_info.get("context_size", 1_000_000)
    provider = model_info.get("provider", "openrouter")

    user_indices = [i for i, m in enumerate(req.messages) if m.role == "user"]
    if user_indices:
        last_idx = user_indices[-1]
        last_user_msg = req.messages[last_idx].text
        history_msgs = req.messages[:last_idx]
    else:
        last_user_msg = req.messages[-1].text if req.messages else ""
        history_msgs = req.messages[:-1]

    history = [{"role": m.role, "content": m.text} for m in history_msgs]

    if req.stream:
        return StreamingResponse(
            stream_sku_agent_response(
                query=last_user_msg,
                history_messages=history,
                model_info=model_info,
                selected_item_id=req.selected_item_id,
                language=req.language or "en",
                session_id=req.session_id,
            ),
            media_type="text/event-stream",
            headers={
                "Cache-Control": "no-cache",
                "Connection": "keep-alive",
                "X-Accel-Buffering": "no",
            },
        )

    accumulated_text = []
    tokens_count = 0
    async for sse in stream_sku_agent_response(
        query=last_user_msg,
        history_messages=history,
        model_info=model_info,
        selected_item_id=req.selected_item_id,
        language=req.language or "en",
        session_id=req.session_id,
    ):
        for sse_line in sse.splitlines():
            line = sse_line.strip()
            if line.startswith("data: "):
                try:
                    payload = json.loads(line[6:].strip())
                    if payload.get("type") == "token":
                        accumulated_text.append(payload.get("content", ""))
                    elif payload.get("type") == "done":
                        tokens_count = payload.get("used_tokens", tokens_count)
                except Exception:
                    pass

    full_reply = "".join(accumulated_text).strip()
    history_tokens = sum(estimate_tokens(m.get("content", "")) for m in history)
    fallback_tokens = history_tokens + estimate_tokens(last_user_msg) + estimate_tokens(full_reply)
    return ChatResponse(
        reply=full_reply or "DemandAI Assistant: Analysis complete.",
        model=model_key,
        provider=provider,
        used_tokens=tokens_count or fallback_tokens,
        context_size=250_000,
        compacted=False,
    )


